"""Ken Burns route.

Turns a still image (generated by Krea 2 in ComfyUI) into a short video clip
with a slow zoom/pan via ffmpeg `zoompan`, so a "static" shot becomes gentle
motion for almost no cost. The clip is produced at the shot's slot length so the
export never has to freeze or pad it.

Variety: instead of one uniform center zoom-in, each shot gets a deterministic
variant (zoom in / zoom out / pan in 4 directions) with smoothstep easing, and
an optional handheld micro-jitter for documentary-style footage. Identical
motion on every still is the tell-tale of template automation; alternating
eased moves reads as an editor's hand.

Pure ffmpeg wrapper — no ComfyUI/LM dependency here; the caller generates the
image and passes its path in.
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

from core.process import run_captured

VIDEO_W = 1920
VIDEO_H = 1080

VARIANTS = ("in", "out", "pan_right", "in", "pan_left", "out", "pan_down", "pan_up")


def pick_variant(shot_index: int) -> str:
    """Deterministic variant per shot: stable across re-renders, varied across
    the timeline (zooms twice as frequent as pans, which suits most footage)."""
    return VARIANTS[int(shot_index) % len(VARIANTS)]


def _eased(total: int) -> str:
    """Smoothstep progress 0..1 over the clip: p*p*(3-2p), no jerky start/stop."""
    p = f"(on/{total})"
    return f"({p}*{p}*(3-2*{p}))"


def build_kenburns_clip(
    image: Path,
    dst: Path,
    ffmpeg: str,
    seconds: float,
    fps: int = 25,
    direction: str = "in",
    max_zoom: float = 1.15,
    jitter: bool = False,
    cancel_check: Callable[[], object] | None = None,
) -> Path:
    """Render a `seconds`-long 1920x1080 clip that slowly moves across `image`.

    direction: "in" / "out" (eased zoom), or "pan_left" / "pan_right" /
    "pan_up" / "pan_down" (eased pan at a slight fixed zoom). `jitter` adds a
    tiny two-frequency handheld wobble (a few pixels at 2x prescale) so the
    move doesn't feel machine-perfect — meant for documentary-style stills.
    The image is pre-scaled to 2x output so the motion stays sharp and zoompan
    doesn't jitter on its own. Audio is dropped — the export stage handles
    voice and music.
    """
    ff = ffmpeg or "ffmpeg"
    dur = max(0.5, float(seconds))
    total = max(2, round(dur * fps))
    ease = _eased(total)
    mode = (direction or "in").lower()

    # Handheld micro-wobble: two incommensurate sine frequencies, +-~4px at the
    # 2x prescale (~2px on screen) — visible as life, not as shake.
    jx = f"+2.5*sin(on/7.3)+1.5*sin(on/2.9)" if jitter else ""
    jy = f"+2.0*sin(on/9.1)+1.2*sin(on/3.7)" if jitter else ""

    center_x = f"iw/2-(iw/zoom/2){jx}"
    center_y = f"ih/2-(ih/zoom/2){jy}"

    if mode.startswith("pan_"):
        # Fixed slight zoom so there is room to travel; eased x/y across it.
        pan_zoom = min(max(1.06, (float(max_zoom) - 1.0) * 0.8 + 1.0), 1.25)
        z_expr = f"{pan_zoom:.4f}"
        span_x = "(iw-iw/zoom)"
        span_y = "(ih-ih/zoom)"
        if mode == "pan_right":
            x_expr, y_expr = f"{span_x}*{ease}{jx}", center_y
        elif mode == "pan_left":
            x_expr, y_expr = f"{span_x}*(1-{ease}){jx}", center_y
        elif mode == "pan_down":
            x_expr, y_expr = center_x, f"{span_y}*{ease}{jy}"
        else:  # pan_up
            x_expr, y_expr = center_x, f"{span_y}*(1-{ease}){jy}"
    elif mode == "out":
        z_expr = f"{max_zoom:.4f}-({max_zoom:.4f}-1.0)*{ease}"
        x_expr, y_expr = center_x, center_y
    else:  # "in"
        z_expr = f"1.0+({max_zoom:.4f}-1.0)*{ease}"
        x_expr, y_expr = center_x, center_y

    # Pre-scale to 2x output (cover), then zoompan down to 1920x1080.
    vf = (
        f"scale={VIDEO_W * 2}:{VIDEO_H * 2}:force_original_aspect_ratio=increase,"
        f"crop={VIDEO_W * 2}:{VIDEO_H * 2},"
        f"zoompan=z='{z_expr}':d={total}:"
        f"x='{x_expr}':y='{y_expr}':"
        f"s={VIDEO_W}x{VIDEO_H}:fps={fps},"
        f"format=yuv420p"
    )

    dst.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        ff, "-y",
        "-loop", "1", "-i", str(image),
        "-t", f"{dur:.2f}",
        "-vf", vf,
        "-r", str(fps),
        "-an", "-c:v", "libx264", "-preset", "veryfast", "-crf", "20",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart",
        str(dst),
    ]
    proc = run_captured(cmd, timeout=600, cancel_check=cancel_check)
    if proc.returncode != 0 or not dst.exists():
        raise RuntimeError(f"ffmpeg Ken Burns failed: {proc.stderr[-400:] if proc.stderr else 'unknown error'}")
    return dst
