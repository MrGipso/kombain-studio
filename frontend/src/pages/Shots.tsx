import { useState, useEffect } from 'react'
import { useOutletContext } from 'react-router-dom'
import * as api from '../api/client'
import { useSSE } from '../hooks/useSSE'
import { useToast } from '../components/toast-context'
import type { Shot, AssetCard } from '../api/types'

interface Context {
  projectId: string
  busy: string | null
  setBusy: (busy: string | null) => void
}

export default function Shots() {
  const { projectId, busy, setBusy } = useOutletContext<Context>()
  const { startStream } = useSSE()
  const toast = useToast()
  const [shots, setShots] = useState<Shot[]>([])
  const [selected, setSelected] = useState<Shot | null>(null)
  const [logs, setLogs] = useState<string[]>([])
  const [running, setRunning] = useState(false)
  const [progress, setProgress] = useState<number | null>(null)
  const [hasScenes, setHasScenes] = useState(false)
  const [shotMode, setShotMode] = useState('ai')
  const [routePriority, setRoutePriority] = useState('balanced')
  const [stockCut, setStockCut] = useState(5)
  const lockedElsewhere = Boolean(busy) && !running

  useEffect(() => {
    api.getShots(projectId).then((d) => {
      const s = d as Shot[]
      setShots(s)
      if (s.length > 0) setSelected((current) => current || s[0])
    }).catch((e) => toast.error(`Не удалось загрузить шоты: ${(e as Error).message}`))
    api.getScenes(projectId).then((d) => {
      setHasScenes(Array.isArray(d) && d.length > 0)
    }).catch(() => {})
    api.getProject(projectId).then((d) => {
      setShotMode(d.shot_mode || 'ai')
      setRoutePriority(d.route_priority || 'balanced')
      setStockCut(d.stock_cut_seconds ?? 5)
    }).catch(() => {})
  }, [projectId, toast])

  const saveMode = (mode: string, cut: number, priority = routePriority) => {
    api.updateProjectSettings(projectId, { shot_mode: mode, route_priority: priority, stock_cut_seconds: cut })
      .catch((e) => toast.error(`Сохранение режима кадров: ${(e as Error).message}`))
  }

  const MODES: { key: string; label: string; hint: string }[] = [
    { key: 'ai', label: 'AI', hint: 'всё нейросетью (Krea + LTX)' },
    { key: 'stock', label: 'Стоки', hint: 'всё из стоков, кусками ≤N сек' },
    { key: 'hybrid', label: 'Гибрид', hint: 'LM Studio сама распределяет: сток / зум / AI' },
  ]
  // Same selector, mode-specific semantics: hybrid = stock/zoom/AI, AI mode =
  // zoom/LTX (style stays fully generated, animation only where motion matters).
  const ROUTE_PRIORITIES: { key: string; label: string; hint: string }[] = shotMode === 'ai' ? [
    { key: 'economy', label: 'Экономно', hint: 'LTX ≤30% времени: анимация только там, где движение несёт смысл; остальное — Krea-стилл с зумом' },
    { key: 'balanced', label: 'Баланс', hint: 'примерно половина времени — живые LTX-кадры, половина — стиллы с зумом' },
    { key: 'rich', label: 'Богато', hint: 'всё анимируется LTX (максимальное качество и время)' },
  ] : [
    { key: 'economy', label: 'Экономно', hint: 'максимум стока и зума, AI только когда без него нельзя' },
    { key: 'balanced', label: 'Баланс', hint: 'дешёвый уместный маршрут, AI для важных/неснимаемых кадров' },
    { key: 'rich', label: 'Богато', hint: 'чаще AI-видео для выразительности и ключевых моментов' },
  ]

  const handleGenerate = () => {
    if (busy) { toast.error('Дождитесь завершения текущей задачи'); return }
    setRunning(true)
    setBusy('Шот-лист')
    setProgress(0)
    setShots([])
    setSelected(null)
    setLogs((prev) => [...prev, '⏳ Генерация шот-листа...'])

    startStream(api.startShotGeneration(projectId), {
      onLog: (msg) => setLogs((prev) => [...prev, msg]),
      onProgress: (_step, value) => { if (typeof value === 'number') setProgress(value) },
      // Live preview: append shots as each scene is generated by the LLM.
      // These are preliminary; onDone replaces the list with the final, normalized one.
      onEvent: (event, data) => {
        if (event === 'scene_shots' && Array.isArray(data.shots)) {
          const incoming = data.shots as Shot[]
          setShots((prev) => {
            const next = [...prev, ...incoming]
            return next
          })
          setSelected((cur) => cur || (incoming.length ? incoming[0] : cur))
        }
      },
      onDone: (data) => {
        const s = data.shots as Shot[]
        const c = data.cards as AssetCard[]
        setShots(s)
        if (s.length > 0) setSelected(s[0])
        setLogs((prev) => [...prev, `✅ Шотов: ${s.length}, карточек: ${c.length}`])
        toast.success(`Шот-лист готов: ${s.length} кадров`)
        setRunning(false)
        setBusy(null)
        setProgress(null)
      },
      onError: (msg) => {
        setLogs((prev) => [...prev, `❌ ${msg}`])
        toast.error(`Шот-лист: ${msg}`)
        setRunning(false)
        setBusy(null)
        setProgress(null)
      },
    })
  }

  // Rebuilds the board structure WITHOUT wiping generation status/outputs of
  // existing cards (matched by shot_index). Confirmed because it can drop cards
  // that no longer correspond to a shot.
  const handleRebuildBoard = async () => {
    if (busy) { toast.error('Дождитесь завершения текущей задачи'); return }
    if (!window.confirm('Пересобрать доску кадров из шот-листа? Существующие статусы и сгенерированные файлы сохранятся для совпадающих кадров.')) {
      return
    }
    try {
      setLogs((prev) => [...prev, '⏳ Пересборка доски кадров...'])
      const existing = await api.getAssetBoard(projectId)
      const result = await api.rebuildAssetBoard(projectId)
      const removed = Math.max(0, existing.length - result.cards.length)
      const suffix = removed ? `, удалено устаревших: ${removed}` : ''
      setLogs((prev) => [...prev, `✅ Доска пересобрана: ${result.count} карточек (статусы сохранены${suffix})`])
      toast.success(`Доска пересобрана: ${result.count} карточек`)
    } catch (e) {
      setLogs((prev) => [...prev, `❌ Ошибка: ${(e as Error).message}`])
      toast.error(`Пересборка: ${(e as Error).message}`)
    }
  }

  const shotFields: { key: keyof Shot; label: string; multiline?: boolean }[] = [
    { key: 'visual_type', label: 'Тип' },
    { key: 'start', label: 'Начало' },
    { key: 'end', label: 'Конец' },
    { key: 'image_model', label: 'Image model' },
    { key: 'video_model', label: 'Video model' },
    { key: 'motion', label: 'Motion' },
    { key: 'priority', label: 'Priority' },
    { key: 'fallback', label: 'Fallback' },
    { key: 'screen_text', label: 'Текст на экране', multiline: true },
    { key: 'description', label: 'Описание', multiline: true },
    { key: 'asset_query', label: 'Asset query', multiline: true },
    { key: 'image_prompt', label: 'Image prompt', multiline: true },
    { key: 'video_prompt', label: 'Video prompt', multiline: true },
  ]

  return (
    <div className="p-8 space-y-6">
      <h1 className="text-2xl font-bold text-white">Шот-лист</h1>

      <div className="flex flex-wrap items-center gap-4 rounded-xl bg-slate-900 border border-slate-800 p-4">
        <span className="text-sm text-slate-400">Режим кадров:</span>
        <div className="flex rounded-lg overflow-hidden border border-slate-700">
          {MODES.map((m) => (
            <button
              key={m.key}
              onClick={() => { setShotMode(m.key); saveMode(m.key, stockCut) }}
              title={m.hint}
              className={`px-4 py-1.5 text-sm font-semibold transition-colors ${
                shotMode === m.key ? 'bg-indigo-600 text-white' : 'bg-slate-800 text-slate-300 hover:bg-slate-700'
              }`}
            >
              {m.label}
            </button>
          ))}
        </div>
        {(shotMode === 'hybrid' || shotMode === 'ai') && (
          <>
            <span className="text-sm text-slate-400">Приоритет:</span>
            <div className="flex rounded-lg overflow-hidden border border-slate-700">
              {ROUTE_PRIORITIES.map((p) => (
                <button
                  key={p.key}
                  onClick={() => { setRoutePriority(p.key); saveMode(shotMode, stockCut, p.key) }}
                  title={p.hint}
                  className={`px-3 py-1.5 text-sm font-semibold transition-colors ${
                    routePriority === p.key ? 'bg-teal-700 text-white' : 'bg-slate-800 text-slate-300 hover:bg-slate-700'
                  }`}
                >
                  {p.label}
                </button>
              ))}
            </div>
          </>
        )}
        <div className="flex items-center gap-2">
          <span className="text-xs text-slate-500">Длина сток-куска ≤</span>
          <input
            type="number"
            min={2}
            max={15}
            value={stockCut}
            disabled={shotMode === 'ai'}
            onChange={(e) => { const v = Math.max(2, Number(e.target.value) || 5); setStockCut(v); saveMode(shotMode, v) }}
            className="w-16 px-2 py-1 bg-slate-800 border border-slate-700 rounded text-white text-sm font-mono disabled:opacity-40"
          />
          <span className="text-xs text-slate-500">сек</span>
        </div>
        <span className="text-xs text-slate-600">{MODES.find((m) => m.key === shotMode)?.hint}. Режим применяется при генерации шот-листа.</span>
      </div>

      <div className="flex gap-3">
        <button
          onClick={handleGenerate}
          disabled={running || lockedElsewhere || !hasScenes}
          className="flex-1 py-3 bg-indigo-600 hover:bg-indigo-500 text-white font-bold rounded-lg disabled:opacity-50 transition-colors cursor-pointer"
        >
          {running ? '⏳ Генерация...' : '🎬 Сгенерировать шот-лист'}
        </button>
        <button
          onClick={handleRebuildBoard}
          disabled={shots.length === 0 || running || lockedElsewhere}
          className="py-3 px-6 bg-emerald-700 hover:bg-emerald-600 text-white font-semibold rounded-lg disabled:opacity-50 transition-colors cursor-pointer"
        >
          📋 Пересобрать доску
        </button>
      </div>

      {lockedElsewhere && (
        <div className="bg-sky-900/30 border border-sky-700/50 rounded-xl p-4 text-sky-300 text-sm">
          ⏳ Идёт другая задача ({busy}). Дождитесь завершения.
        </div>
      )}

      {!hasScenes && !running && (
        <div className="bg-amber-900/30 border border-amber-700/50 rounded-xl p-4 text-amber-300 text-sm">
          ⚠️ Сначала выполните анализ сцен.
        </div>
      )}

      {running && (
        <div className="flex items-center gap-3 px-4 py-3 bg-indigo-900/40 border border-indigo-700/50 rounded-lg">
          <span className="w-3 h-3 rounded-full bg-indigo-400 animate-ping" />
          <span className="text-indigo-300 text-sm font-semibold shrink-0">
            Генерация кадров… {progress !== null ? `${Math.round(progress * 100)}%` : `(${shots.length})`}
          </span>
          <button
            onClick={() => api.cancelJob(projectId).then(() => toast.info('Отмена — остановится после текущей сцены')).catch(() => {})}
            className="shrink-0 text-xs px-3 py-1 rounded bg-rose-800 hover:bg-rose-700 text-white cursor-pointer"
          >
            Отменить
          </button>
          <div className="flex-1 h-1.5 bg-slate-700 rounded-full overflow-hidden">
            {progress !== null ? (
              <div className="h-full bg-indigo-500 rounded-full transition-all" style={{ width: `${Math.round(progress * 100)}%` }} />
            ) : (
              <div className="h-full w-1/3 bg-indigo-500 rounded-full animate-[indeterminate_1.2s_ease-in-out_infinite]" />
            )}
          </div>
        </div>
      )}

      {shots.length > 0 && (
        <div className="grid grid-cols-[1fr_400px] gap-6">
          {/* Shot table */}
          <div className="bg-slate-900 rounded-xl border border-slate-800 overflow-hidden">
            <div className="overflow-auto max-h-[65vh]">
              <table className="w-full text-sm">
                <thead className="sticky top-0 bg-slate-900">
                  <tr className="text-slate-500 text-xs uppercase border-b border-slate-800">
                    <th className="text-left px-3 py-2 w-12">#</th>
                    <th className="text-left px-3 py-2 w-14">Сцена</th>
                    <th className="text-left px-3 py-2 w-36">Время</th>
                    <th className="text-left px-3 py-2 w-28">Тип</th>
                    <th className="text-left px-3 py-2">Модель</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-800">
                  {shots.map((shot) => (
                    <tr
                      key={shot.index}
                      onClick={() => setSelected(shot)}
                      className={`cursor-pointer transition-colors ${
                        selected?.index === shot.index
                          ? 'bg-indigo-600/20'
                          : 'hover:bg-slate-800/50'
                      }`}
                    >
                      <td className="px-3 py-2 text-slate-400 font-mono text-xs">{shot.index}</td>
                      <td className="px-3 py-2 text-slate-500">{shot.scene_index}</td>
                      <td className="px-3 py-2 text-slate-300 font-mono text-xs">{shot.start} – {shot.end}</td>
                      <td className="px-3 py-2">
                        <span className="text-xs bg-slate-700 px-2 py-0.5 rounded text-slate-300">{shot.visual_type}</span>
                      </td>
                      <td className="px-3 py-2 text-slate-500 text-xs">{shot.image_model || shot.video_model || '-'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          {/* Shot detail */}
          {selected && (
            <div className="bg-slate-900 rounded-xl p-5 border border-slate-800 space-y-3 overflow-auto max-h-[65vh]">
              <div className="flex items-center justify-between gap-2">
                <h2 className="text-lg font-semibold text-white">Кадр {selected.index} <span className="text-sm text-slate-500 font-normal">(Сцена {selected.scene_index})</span></h2>
                <span className="rounded bg-slate-800 px-2 py-1 text-[11px] text-slate-400 border border-slate-700">только просмотр · правка на Asset Board</span>
              </div>
              <div className="space-y-2.5">
                {shotFields.map(({ key, label, multiline }) => (
                  <div key={key}>
                    <label className="block text-xs text-slate-500 mb-0.5">{label}</label>
                    {multiline ? (
                      <div className="text-sm text-slate-300 bg-slate-800/50 rounded px-3 py-2 whitespace-pre-wrap min-h-[2.5rem]">
                        {(selected[key] as string) || '—'}
                      </div>
                    ) : (
                      <div className="text-sm text-slate-300">{((selected[key] as string) || '—').toString()}</div>
                    )}
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}

      {/* Logs */}
      <div className="bg-slate-900/50 rounded-xl p-4 border border-slate-800">
        <h3 className="text-sm text-slate-500 mb-2">Логи</h3>
        <div className="max-h-32 overflow-y-auto text-xs text-slate-500 space-y-0.5 font-mono">
          {logs.map((l, i) => (<div key={i}>{l}</div>))}
          {logs.length === 0 && <div className="text-slate-700">Ожидание...</div>}
        </div>
      </div>
    </div>
  )
}
